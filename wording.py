def pick(key: str, **kwargs: Any) -> str:
    """按 key 随机取一条文案并填充占位符。"""
    choices = _TEMPLATES.get(key)
    if not choices:
        raise KeyError(f"没有这一类文案:{key}")
    tpl = random.choice(choices)
    return tpl.format(**kwargs) if kwargs else tpl


def count() -> int:
    """返回总变体数量,方便自检。"""
    return sum(len(v) for v in _TEMPLATES.values())
